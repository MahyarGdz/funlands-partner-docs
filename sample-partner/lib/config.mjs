/** Provisioned identifiers written by setup/register (partner id, api key, client id, game id, admin login). */
export function readState() {
  if (!existsSync(paths.state)) return {};
  return JSON.parse(readFileSync(paths.state, "utf8"));
}

export function writeState(patch) {
  mkdirSync(DEMO_DIR, { recursive: true });
  const next = { ...readState(), ...patch };
  writeFileSync(paths.state, JSON.stringify(next, null, 2), { mode: 0o600 });
  return next;
}

export function requireState(...keys) {
  const state = readState();
  const missing = keys.filter((key) => state[key] === undefined);
  if (missing.length > 0) throw new Error(`demo state is missing ${missing.join(", ")}: run \`npm run up\` first`);
  return state;
}
