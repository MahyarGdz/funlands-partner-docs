// Provisions everything the backend needs before it starts (idempotent):
//   keys (partner ES256 key, Funlands PARTNER_SIGNING_KEY_DIR), demo TLS CA + partner certificate, .backend.env,
//   backend migrations on the demo database, a platform admin account and one active game.
//   node scripts/setup.mjs [--reset]   (--reset drops and recreates the demo database and forgets the registration)
import { generateKeyPairSync, randomBytes, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import bcrypt from "bcryptjs";
import {
  BACKEND_DIR, BACKEND_ENV_FILE, DATABASE_NAME, DATABASE_URL, DEMO_DIR, FUNLANDS_SIGNING_KID, GAME_ORIGIN,
  GAME_PATH_TEMPLATE, PARTNER, PARTNER_HOST, PORTS, paths, readState, writeState,
} from "../lib/config.mjs";
import { run } from "../lib/proc.mjs";

const reset = process.argv.includes("--reset");
const psqlArgs = (db) => ["-h", "127.0.0.1", "-p", String(PORTS.postgres), "-U", "postgres", "-d", db, "-v", "ON_ERROR_STOP=1"];
const psql = (sql, db = DATABASE_NAME) => run(join(paths.pgBin, "psql"), [...psqlArgs(db), "-Atc", sql], { quiet: true }).stdout.trim();

function ecKey(file) {
  if (existsSync(file)) return false;
  const { privateKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
  writeFileSync(file, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600, flag: "wx" });
  return true;
}

function keys() {
  mkdirSync(paths.partnerKeys, { recursive: true, mode: 0o700 });
  mkdirSync(paths.funlandsKeys, { recursive: true, mode: 0o700 });
  if (ecKey(join(paths.partnerKeys, `${PARTNER.kid}.pem`))) console.log(`partner signing key ${PARTNER.kid} generated`);
  if (ecKey(join(paths.funlandsKeys, `${FUNLANDS_SIGNING_KID}.pem`))) console.log(`Funlands signing key ${FUNLANDS_SIGNING_KID} generated`);
}

function tls() {
  mkdirSync(paths.tls, { recursive: true, mode: 0o700 });
  if (existsSync(paths.partnerCert)) return;
  const dir = paths.tls;
  const openssl = (args) => run("openssl", args, { quiet: true, cwd: dir });
  openssl(["ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "demo-ca-key.pem"]);
  openssl(["req", "-x509", "-new", "-key", "demo-ca-key.pem", "-sha256", "-days", "365", "-subj", "/CN=Funlands sample partner DEMO CA",
    "-addext", "basicConstraints=critical,CA:TRUE", "-addext", "keyUsage=critical,keyCertSign,cRLSign", "-out", "demo-ca.pem"]);
  openssl(["ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "partner-key.pem"]);
  openssl(["req", "-new", "-key", "partner-key.pem", "-subj", `/CN=${PARTNER_HOST}`, "-out", "partner.csr"]);
  writeFileSync(join(dir, "partner.ext"), [
    "basicConstraints=critical,CA:FALSE",
    "keyUsage=critical,digitalSignature",
    "extendedKeyUsage=serverAuth",
    `subjectAltName=DNS:${PARTNER_HOST},IP:127.0.0.1`,
  ].join("\n"));
  openssl(["x509", "-req", "-in", "partner.csr", "-CA", "demo-ca.pem", "-CAkey", "demo-ca-key.pem", "-CAcreateserial",
    "-days", "365", "-sha256", "-extfile", "partner.ext", "-out", "partner.pem"]);
  console.log(`demo TLS CA and ${PARTNER_HOST} certificate generated in ${dir}`);
}

function secrets() {
  const state = readState();
  if (state.secrets) return state.secrets;
  const secret = () => randomBytes(32).toString("base64url");
  return writeState({ secrets: { jwt: secret(), otpPepper: secret(), apiKeyPepper: secret() } }).secrets;
}

function backendEnv(secret) {
  const redis = (db) => `redis://127.0.0.1:${PORTS.redis}/${db}`;
  const lines = {
    "# DEMO ONLY": "generated by sample-partner/scripts/setup.mjs; never use these values outside this machine",
    PORT: PORTS.backend,
    LOG_LEVEL: "info",
    PROCESS_ROLE: "all",
    DATABASE_URL,
    JWT_SECRET: secret.jwt,
    OTP_PEPPER: secret.otpPepper,
    PARTNER_API_KEY_PEPPER: secret.apiKeyPepper,
    REDIS_CACHE_URL: redis(0),
    REDIS_OTP_URL: redis(1),
    REDIS_LEADERBOARD_URL: redis(2),
    REDIS_REALTIME_URL: redis(3),
    SMSIR_ENABLED: "false",
    PARTNER_SIGNING_KEY_DIR: paths.funlandsKeys,
    PARTNER_SIGNING_ACTIVE_KID: FUNLANDS_SIGNING_KID,
    PARTNER_GAME_ORIGIN: GAME_ORIGIN,
    PARTNER_GAME_PATH_TEMPLATE: GAME_PATH_TEMPLATE,
    // Demo-only generous budgets: every call reaches the backend from 127.0.0.1 (one IP), and e2e runs repeat.
    HTTP_RATE_LIMIT_MAX: 10000,
    HTTP_AUTH_RATE_LIMIT_MAX: 10000,
    HTTP_RESTRICTED_RATE_LIMIT_MAX: 10000,
    HTTP_STRICT_RATE_LIMIT_MAX: 10000,
    HTTP_CRITICAL_RATE_LIMIT_MAX: 10000,
    PARTNER_LAUNCH_RATE_LIMIT_MAX: 10000,
    PARTNER_TOKEN_RATE_LIMIT_MAX: 10000,
    PARTNER_API_RATE_LIMIT_MAX: 10000,
    PARTNER_RESOLVE_RATE_LIMIT_MAX: 10000,
    OUTBOX_POLL_INTERVAL_MS: 500,
    OBJECT_STORAGE_LOCAL_ROOT: join(DEMO_DIR, "object-storage"),
    // Read by scripts/backend.mjs (not by Funlands): the demo-only loopback shim and the demo CA it must trust.
    FUNLANDS_DEMO_LOOPBACK_HOSTS: PARTNER_HOST,
    NODE_EXTRA_CA_CERTS: paths.caCert,
  };
  const body = Object.entries(lines)
    .map(([key, value]) => (key.startsWith("#") ? `${key}: ${value}` : `${key}=${value}`))
    .join("\n");
  writeFileSync(BACKEND_ENV_FILE, `${body}\n`, { mode: 0o600 });
  console.log(`backend env written to ${BACKEND_ENV_FILE}`);
}

function resetDatabase() {
  psql(`select pg_terminate_backend(pid) from pg_stat_activity where datname='${DATABASE_NAME}' and pid <> pg_backend_pid()`, "postgres");
  psql(`drop database if exists ${DATABASE_NAME}`, "postgres");
  psql(`create database ${DATABASE_NAME}`, "postgres");
  const { secrets: kept } = readState();
  writeFileSync(paths.state, JSON.stringify({ secrets: kept }, null, 2), { mode: 0o600 });
  console.log(`database ${DATABASE_NAME} recreated; registration state cleared`);
}

function migrate() {
  if (!existsSync(join(BACKEND_DIR, "node_modules"))) throw new Error(`backend dependencies missing in ${BACKEND_DIR} (pnpm install)`);
  console.log("running backend migrations (TypeORM ledger, then MikroORM)…");
  const result = run("pnpm", ["run", "migration:run"], {
    cwd: BACKEND_DIR,
    env: { ...process.env, DATABASE_URL },
    quiet: true,
  });
  const lines = `${result.stdout}`.trim().split("\n");
  console.log(`  ${lines.at(-1)}`);
}

function seed() {
  const state = readState();
  const admin = state.admin ?? { id: randomUUID(), userName: "demo_admin", password: randomBytes(18).toString("base64url") };
  const hash = bcrypt.hashSync(admin.password, 10);
  // Platform admin = identity.users.is_admin on a non-partner, non-guest account (checked from the database by the
  // admin API on every call). There is no admin sign-up endpoint; operators set the flag.
  psql(`insert into identity.users (id, user_name, is_guest, is_admin, is_active, partner_id, password_hash)
        values ('${admin.id}', '${admin.userName}', false, true, true, null, '${hash}')
        on conflict (id) do update set is_admin = true, is_active = true, password_hash = excluded.password_hash`);
  const game = state.game ?? { id: randomUUID(), title: "Star Runner (demo)" };
  psql(`insert into game.games (id, creator_user_id, creator_full_name, title, description, is_confirm, is_active, game_infos)
        values ('${game.id}', '${admin.id}', 'Funlands demo', '${game.title}', 'Seeded by the sample partner setup', true, true,
                '{"namayeshBazi": true}'::jsonb)
        on conflict (id) do nothing`);
  writeState({ admin, game });
  console.log(`platform admin ${admin.userName} and game ${game.id} (${game.title}) seeded`);
}

mkdirSync(DEMO_DIR, { recursive: true, mode: 0o700 });
if (reset) resetDatabase();
keys();
tls();
backendEnv(secrets());
migrate();
seed();
console.log("setup done");
